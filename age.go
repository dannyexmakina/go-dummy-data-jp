func GetAgeByRate(rate float64) (age int, e error) {
	if rate < 0 {
		return age, fmt.Errorf("rate cannot be negative")
	}
	if rate > 1 {
		return age, fmt.Errorf("rate cannot be greater than 1")
	}
	for i := range ages {
		if ages[i].Rate >= rate {
			return ages[i].Age, nil
		}
	}
	return age, fmt.Errorf("rate not found")
}
func GetRandomAge() (age int, e error) {
	rate := rand.Float64()
	return GetAgeByRate(rate)
}
